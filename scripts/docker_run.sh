#!/usr/bin/env bash
# Run the riggu dev/sim container (docker/compose.yaml, service "dev") with the
# host's display and GPU detected. Detection results go to a compose override
# file (docker/compose.override.yaml, git-ignored) that .devcontainer/ reuses.
set -euo pipefail

usage() {
  cat <<EOF
Usage: $0 [options] [--] [cmd ...]

Runs cmd (default: interactive bash) in the dev container, workspace at /ws.

  --build             rebuild the image first (also done when it is missing)
  --display MODE      auto|wslg|wayland|x11|none     (env RIGGU_DISPLAY, default auto)
  --gpu MODE          auto|wsl|nvidia|dri|software   (env RIGGU_GPU, default auto)
  --write-override    only write docker/compose.override.yaml and exit
  -h, --help          this help

Env: RIGGU_HOST (default riggu.local); RIGGU_ZENOH_ENDPOINT (default derived
from 'ssh -G \$RIGGU_HOST' on the host, port 7447) for the remote zenoh profile.
EOF
}

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
COMPOSE=(docker compose -f "$ROOT/docker/compose.yaml")
OVERRIDE="$ROOT/docker/compose.override.yaml"
DISPLAY_MODE=${RIGGU_DISPLAY:-auto}
GPU_MODE=${RIGGU_GPU:-auto}
BUILD=0
WRITE_ONLY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --build) BUILD=1; shift ;;
    --display) DISPLAY_MODE=${2:?}; shift 2 ;;
    --gpu) GPU_MODE=${2:?}; shift 2 ;;
    --write-override) WRITE_ONLY=1; shift ;;
    -h | --help) usage; exit 0 ;;
    --) shift; break ;;
    -*) usage >&2; exit 2 ;;
    *) break ;;
  esac
done

log() { printf '[docker_run] %s\n' "$*" >&2; }
has_nvidia_runtime() { docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q '"nvidia"'; }
has_nvidia_gpu() {
  local smi
  for smi in nvidia-smi /usr/lib/wsl/lib/nvidia-smi; do
    if command -v "$smi" &>/dev/null && "$smi" -L &>/dev/null; then return 0; fi
  done
  return 1
}

# --- detection -----------------------------------------------------------------
if [[ $DISPLAY_MODE == auto ]]; then
  if [[ -d /mnt/wslg ]]; then DISPLAY_MODE=wslg
  elif [[ -n ${WAYLAND_DISPLAY:-} && -S ${XDG_RUNTIME_DIR:-/nonexistent}/${WAYLAND_DISPLAY} ]]; then DISPLAY_MODE=wayland
  elif [[ -n ${DISPLAY:-} ]]; then DISPLAY_MODE=x11
  else DISPLAY_MODE=none
  fi
fi
if [[ $GPU_MODE == auto ]]; then
  if [[ -e /dev/dxg ]]; then GPU_MODE=wsl
  elif has_nvidia_gpu && has_nvidia_runtime; then GPU_MODE=nvidia
  elif [[ -d /dev/dri ]]; then GPU_MODE=dri
  else GPU_MODE=software
  fi
fi
log "display=$DISPLAY_MODE gpu=$GPU_MODE"

# --- override file ---------------------------------------------------------------
volumes=()
envs=()
devices=()
nvidia=0
case "$DISPLAY_MODE" in
  wslg)
    volumes+=("/tmp/.X11-unix:/tmp/.X11-unix" "/mnt/wslg:/mnt/wslg")
    envs+=("DISPLAY=${DISPLAY:-:0}" "WAYLAND_DISPLAY=${WAYLAND_DISPLAY:-wayland-0}"
      "XDG_RUNTIME_DIR=/mnt/wslg/runtime-dir" "PULSE_SERVER=${PULSE_SERVER:-unix:/mnt/wslg/PulseServer}") ;;
  wayland)
    volumes+=("$XDG_RUNTIME_DIR/$WAYLAND_DISPLAY:/tmp/runtime-riggu/$WAYLAND_DISPLAY")
    envs+=("WAYLAND_DISPLAY=$WAYLAND_DISPLAY" "XDG_RUNTIME_DIR=/tmp/runtime-riggu" "QT_QPA_PLATFORM=wayland;xcb")
    if [[ -n ${DISPLAY:-} ]]; then
      volumes+=("/tmp/.X11-unix:/tmp/.X11-unix")
      envs+=("DISPLAY=$DISPLAY")
    fi ;;
  x11)
    volumes+=("/tmp/.X11-unix:/tmp/.X11-unix")
    envs+=("DISPLAY=$DISPLAY")
    if [[ -f ${XAUTHORITY:-$HOME/.Xauthority} ]]; then
      volumes+=("${XAUTHORITY:-$HOME/.Xauthority}:/tmp/.Xauthority:ro")
      envs+=("XAUTHORITY=/tmp/.Xauthority")
    fi ;;
  none) ;;
  *) echo "error: unknown display mode $DISPLAY_MODE" >&2; exit 2 ;;
esac
case "$GPU_MODE" in
  wsl)
    # Mesa's d3d12 driver renders through /dev/dxg on the Windows GPU.
    devices+=("/dev/dxg:/dev/dxg")
    volumes+=("/usr/lib/wsl:/usr/lib/wsl:ro")
    envs+=("LD_LIBRARY_PATH=/usr/lib/wsl/lib" "GALLIUM_DRIVER=d3d12")
    if has_nvidia_gpu; then envs+=("MESA_D3D12_DEFAULT_ADAPTER_NAME=NVIDIA"); fi ;;
  nvidia)
    nvidia=1
    envs+=("NVIDIA_DRIVER_CAPABILITIES=all" "__GLX_VENDOR_LIBRARY_NAME=nvidia") ;;
  dri) devices+=("/dev/dri:/dev/dri") ;;
  software) envs+=("LIBGL_ALWAYS_SOFTWARE=1") ;;
  *) echo "error: unknown gpu mode $GPU_MODE" >&2; exit 2 ;;
esac

# Remote zenoh endpoint: resolve the Pi's real host name with the host's ssh config.
RIGGU_HOST=${RIGGU_HOST:-riggu.local}
if [[ -z ${RIGGU_ZENOH_ENDPOINT:-} ]] && command -v ssh &>/dev/null; then
  pi=$(ssh -G "$RIGGU_HOST" 2>/dev/null | awk '$1=="hostname"{print $2; exit}')
  RIGGU_ZENOH_ENDPOINT="tcp/${pi:-$RIGGU_HOST}:7447"
fi
envs+=("RIGGU_HOST=$RIGGU_HOST" "RIGGU_ZENOH_ENDPOINT=${RIGGU_ZENOH_ENDPOINT:-}")

{
  echo "# Generated by scripts/docker_run.sh (display=$DISPLAY_MODE gpu=$GPU_MODE). Do not edit."
  echo "services:"
  echo "  dev:"
  if ((${#volumes[@]})); then echo "    volumes:"; printf '      - "%s"\n' "${volumes[@]}"; fi
  if ((${#devices[@]})); then echo "    devices:"; printf '      - "%s"\n' "${devices[@]}"; fi
  echo "    environment:"; printf '      - "%s"\n' "${envs[@]}"
  if ((nvidia)); then
    cat <<EOF
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: all
              capabilities: [gpu]
EOF
  fi
} >"$OVERRIDE"
[[ $WRITE_ONLY == 1 ]] && exit 0

# --- run ---------------------------------------------------------------------------
RIGGU_UID=$(id -u)
RIGGU_GID=$(id -g)
export RIGGU_UID RIGGU_GID
COMPOSE+=(-f "$OVERRIDE")
if [[ $BUILD == 1 ]] || ! docker image inspect riggu_ws:jazzy-dev &>/dev/null; then
  "${COMPOSE[@]}" build dev
fi
tty=()
[[ -t 0 && -t 1 ]] || tty=(-T)
if [[ $# -eq 0 ]]; then set -- bash; fi
exec "${COMPOSE[@]}" run --rm "${tty[@]}" dev "$@"
